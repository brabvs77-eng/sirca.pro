const WP = 'woodperfect.ru, открытая витрина Sirca, сентябрь 2026';

export type SircaProduct = {
  sku: string;
  slug: string;
  brand: 'sirca';
  name: string;
  short: string;
  description: string;
  tasks: string[];
  use: 'exterior' | 'interior' | 'windows' | 'parquet' | 'furniture' | 'oils';
  chemistry: 'water' | 'pu' | 'acrylic' | 'oil';
  unit: 'л' | 'кг';
  packs: (Pack & { source: string; unit: 'л' | 'кг' })[];
  features: string[];
  hardener?: string;
  priceOnRequest?: boolean;
};

function pack(unit: 'л' | 'кг', liters: number, market: number): (Pack & { source: string; unit: 'л' | 'кг' }) {
  return {
    volume: `1 ${unit}`,
    liters,
    marketPrice: market,
    price: belowMarket(market),
    source: WP,
    unit,
  };
}

